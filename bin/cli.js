function generateServiceJs(name) {
  const Name = cap(name);
  return `'use strict';

// ─── ${Name} Service ──────────────────────────────────────────────────────────────
// Pure business logic. Replace the in-memory store with your DB layer
// (Mongoose, Prisma, TypeORM, Sequelize, etc.)

const { ApiError } = require('express-response-engine');

/** @type {Array<{id: number, name: string, email: string, createdAt: string}>} */
const store = [];
let nextId = 1;

/**
 * Get all ${name}s
 * @returns {Promise<Array>}
 */
const getAll = async () => {
  return store;
};

/**
 * Get a single ${name} by ID
 * @param {string|number} id
 * @returns {Promise<Object>}
 * @throws {ApiError} 404 if not found
 */
const getById = async (id) => {
  const item = store.find((u) => u.id === parseInt(id, 10));
  if (!item) throw ApiError.notFound(\`${Name} with ID \${id} not found\`);
  return item;
};

/**
 * Create a new ${name}
 * @param {{ name: string, email: string, password: string }} data
 * @returns {Promise<Object>}
 * @throws {ApiError} 409 if email already exists
 */
const create = async (data) => {
  const existing = store.find((u) => u.email === data.email);
  if (existing) throw ApiError.conflict(\`Email '\${data.email}' is already registered\`);

  const { password, ...safeData } = data; // never store plain-text passwords in prod
  const item = { id: nextId++, ...safeData, createdAt: new Date().toISOString() };
  store.push(item);
  return item;
};

/**
 * Update an existing ${name}
 * @param {string|number} id
 * @param {Partial<{name: string, email: string}>} data
 * @returns {Promise<Object>}
 * @throws {ApiError} 404 if not found
 */
const update = async (id, data) => {
  const index = store.findIndex((u) => u.id === parseInt(id, 10));
  if (index === -1) throw ApiError.notFound(\`${Name} with ID \${id} not found\`);
  store[index] = { ...store[index], ...data, updatedAt: new Date().toISOString() };
  return store[index];
};

/**
 * Delete a ${name}
 * @param {string|number} id
 * @returns {Promise<void>}
 * @throws {ApiError} 404 if not found
 */
const remove = async (id) => {
  const index = store.findIndex((u) => u.id === parseInt(id, 10));
  if (index === -1) throw ApiError.notFound(\`${Name} with ID \${id} not found\`);
  store.splice(index, 1);
};

module.exports = { getAll, getById, create, update, remove };
`;
}

