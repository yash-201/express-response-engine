//  COMMAND: module
// ════════════════════════════════════════════════════════════════════════════

function runModule(args) {
  const useTs = args.includes('--ts') || args.includes('--typescript');
  const force  = args.includes('--force') || args.includes('-f');
  const cwd    = process.cwd();

  // Extract --dir value
  let customDir = null;
  const dirIdx = args.indexOf('--dir');
  if (dirIdx !== -1 && args[dirIdx + 1] && !args[dirIdx + 1].startsWith('-')) {
    customDir = args[dirIdx + 1];
  }

  // The module name is the first non-flag positional after the command
  const positionals = args.filter(
    (a, i) => !a.startsWith('-') &&
               a !== 'module' && a !== 'create-module' &&
               !(args[i - 1] === '--dir')
  );

  if (positionals.length === 0) {
    console.error(RED('\n✖  Module name is required.\n') +
      `   Usage: ${YELLOW('npx express-response-engine module <name>')}\n`);
    process.exit(1);
  }

  const rawName = positionals[0].toLowerCase().replace(/[^a-z0-9-_]/g, '');
  if (!rawName) {
    console.error(RED('\n✖  Invalid module name. Use lowercase letters, numbers, hyphens or underscores.\n'));
    process.exit(1);
  }

  // Resolve output directory
  let baseDir;
  if (customDir) {
    baseDir = path.resolve(cwd, customDir, rawName);
  } else {
    const base = detectSrcBase(cwd);
    baseDir = path.join(base, 'modules', rawName);
  }

  ensureDir(baseDir);

  const ext = useTs ? 'ts' : 'js';

  const files = [
    {
      name: `${rawName}.validation.${ext}`,
      content: useTs ? generateValidationTs(rawName) : generateValidationJs(rawName),
    },
    {
      name: `${rawName}.service.${ext}`,
      content: useTs ? generateServiceTs(rawName) : generateServiceJs(rawName),
    },
    {
      name: `${rawName}.controller.${ext}`,
      content: useTs ? generateControllerTs(rawName) : generateControllerJs(rawName),
    },
    {
      name: `${rawName}.router.${ext}`,
      content: useTs ? generateRouterTs(rawName) : generateRouterJs(rawName),
    },
  ];

  const created = [];
  for (const file of files) {
    const fullPath = path.join(baseDir, file.name);
    const rel = writeFile(fullPath, file.content, force, cwd);
    created.push(rel);
  }

  const relBase   = path.relative(cwd, baseDir);
  const routerRel = created.find((f) => f.includes('.router.'));
  const mountPath = `/api/${rawName}s`;

  console.log(`
${GREEN('✔')} ${BOLD(`Module '${rawName}' created successfully!`)}

   ${DIM('Created files:')}
${created.map((f) => `   ${CYAN(f)}`).join('\n')}

${BOLD('Next steps:')}
   1. Install dependencies (if not already):
      ${YELLOW('npm install express express-response-engine express-validator')}

   2. Mount the router in your server entry file:
      ${DIM('// In your index.js / app.js')}
      ${YELLOW(`const ${rawName}Router = require('./${relBase}/${rawName}.router');`)}
      ${YELLOW(`app.use('${mountPath}', ${rawName}Router);`)}

${useTs ? `   ${DIM('// TypeScript:')}
      ${YELLOW(`import ${rawName}Router from './${relBase}/${rawName}.router';`)}
      ${YELLOW(`app.use('${mountPath}', ${rawName}Router);`)}
` : ''}
${BOLD('Available endpoints after mounting:')}
   ${CYAN(`GET    ${mountPath}`)}        — list all ${rawName}s
   ${CYAN(`GET    ${mountPath}/:id`)}    — get one ${rawName}
   ${CYAN(`POST   ${mountPath}`)}        — create a ${rawName}
   ${CYAN(`PUT    ${mountPath}/:id`)}    — update a ${rawName}
   ${CYAN(`DELETE ${mountPath}/:id`)}    — delete a ${rawName}

${BOLD('Customise:')}
   • ${DIM(`${rawName}.validation.${ext}`)}  — Add / modify express-validator rules
   • ${DIM(`${rawName}.service.${ext}`)}     — Replace in-memory store with Mongoose / Prisma / TypeORM
   • ${DIM(`${rawName}.controller.${ext}`)} — Adjust response messages and shapes
   • ${DIM(`${rawName}.router.${ext}`)}      — Add auth middleware, extra routes
`);
}

// ════════════════════════════════════════════════════════════════════════════
//  ENTRY POINT
// ════════════════════════════════════════════════════════════════════════════

function main() {
  const args = process.argv.slice(2);

  if (args.length === 0 || args.includes('--help') || args.includes('-h')) {
    printHelp();
    process.exit(0);
  }

  const command = args[0];

  if (command === 'module' || command === 'create-module') {
    runModule(args);
  } else if (
    command === 'init' ||
    command === 'create-server' ||
    command.startsWith('-') ||          // flag-only: treat as init
    command.includes('.')               // explicit file path: treat as init
  ) {
    runInit(args);
  } else {
    console.error(RED(`\n✖  Unknown command: '${command}'\n`) +
      `   Run ${YELLOW('npx express-response-engine --help')} to see available commands.\n`);
    process.exit(1);
  }
}

main();
