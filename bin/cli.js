function ensureDir(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

function writeFile(filePath, content, force, cwd) {
  const rel = path.relative(cwd, filePath);
  if (fs.existsSync(filePath) && !force) {
    console.error(
      RED(`\n\u2716  File already exists: ${rel}`) +
      `\n   Use ${YELLOW('--force')} to overwrite it.\n`
    );
    process.exit(1);
  }
  // Ensure parent directory exists (handles custom paths like server/app.js)
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, 'utf8');
  return rel;
}

function detectSrcBase(cwd) {
  const srcDir = path.join(cwd, 'src');
  return fs.existsSync(srcDir) && fs.statSync(srcDir).isDirectory() ? srcDir : cwd;
}

// ════════════════════════════════════════════════════════════════════════════
//  COMMAND: init
// ════════════════════════════════════════════════════════════════════════════

function runInit(args) {
  const useTs = args.includes('--ts') || args.includes('--typescript');
  const force  = args.includes('--force') || args.includes('-f');
  const cwd    = process.cwd();

  const positionals = args.filter(
    (a) => !a.startsWith('-') && a !== 'init' && a !== 'create-server'
  );

  let outputPath;
  if (positionals.length > 0) {
    outputPath = path.resolve(cwd, positionals[0]);
  } else {
    const base     = detectSrcBase(cwd);
    const fileName = useTs ? 'index.ts' : 'index.js';
    outputPath     = path.join(base, fileName);
  }

  const isTs     = outputPath.endsWith('.ts') || useTs;
  const template = isTs ? generateServerTs() : generateServerJs();
  const relPath  = writeFile(outputPath, template, force, cwd);

  console.log(`
${GREEN('✔')} ${BOLD('Server file created successfully!')}

   ${CYAN(relPath)}

${BOLD('Next steps:')}
   1. Install dependencies (if not already):
      ${YELLOW('npm install express express-response-engine')}

   2. Start your server:
      ${YELLOW(`node ${relPath}`)}${isTs ? `\n      ${YELLOW(`ts-node ${relPath}`)}` : ''}

   3. Health check:
      ${CYAN('http://localhost:3000/health')}

${BOLD('Tip:')} Generate a full module with:
      ${YELLOW(`npx express-response-engine module <name>${isTs ? ' --ts' : ''}`)}
`);
}

