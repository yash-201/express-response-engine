#!/usr/bin/env node

'use strict';

const fs = require('fs');
const path = require('path');

// ─── Helpers ────────────────────────────────────────────────────────────────

const BOLD  = (s) => `\x1b[1m${s}\x1b[0m`;
const GREEN = (s) => `\x1b[32m${s}\x1b[0m`;
const CYAN  = (s) => `\x1b[36m${s}\x1b[0m`;
const YELLOW= (s) => `\x1b[33m${s}\x1b[0m`;
const RED   = (s) => `\x1b[31m${s}\x1b[0m`;

function printHelp() {
  console.log(`
${BOLD('express-response-engine')} - Server Initialization CLI

${BOLD('USAGE')}
  npx express-response-engine init [output-path] [flags]
  npx create-express-server [output-path] [flags]

${BOLD('COMMANDS')}
  init               Scaffold a starter Express server file

${BOLD('FLAGS')}
  --ts, --typescript  Generate a TypeScript file (.ts) instead of JavaScript
  --force, -f         Overwrite an existing file without prompting
  --help, -h          Show this help message

${BOLD('EXAMPLES')}
  npx express-response-engine init
  npx express-response-engine init --ts
  npx express-response-engine init server.js
  npx express-response-engine init src/app.ts --force

${BOLD('OUTPUT LOCATION (auto-detected)')}
  • If a ${CYAN('src/')} directory exists  →  ${CYAN('src/index.js')} (or ${CYAN('src/index.ts')})
  • Otherwise                  →  ${CYAN('index.js')}  (or ${CYAN('index.ts')})
`);
}

// ─── JS Template ────────────────────────────────────────────────────────────

function generateJsTemplate() {
  return `'use strict';

// ──────────────────────────────────────────────────────────────────────────────
// Server scaffold generated by express-response-engine
// Docs: https://github.com/yash-201/express-response-engine
// ──────────────────────────────────────────────────────────────────────────────

const express = require('express');
const {
  responseInterceptor,
  errorInterceptor,
  asyncHandler,
  ApiError,
} = require('express-response-engine');

const app = express();
const PORT = process.env.PORT || 3000;

// ─── Middleware ───────────────────────────────────────────────────────────────

app.use(express.json());
app.use(express.urlencoded({ extended: true }));

// Attaches res.success(), res.created(), res.badRequest(), etc.
// Optionally pass { logger, encrypt, requestIdHeader } for advanced features.
app.use(responseInterceptor());

// ─── Routes ──────────────────────────────────────────────────────────────────

/**
 * GET /health
 * Health check endpoint — bypasses logger and encryption hooks.
 */
app.get('/health', (req, res) => {
  res.check(
    {
      status: 'ok',
      uptime: process.uptime(),
      timestamp: new Date().toISOString(),
    },
    'Server is healthy'
  );
});

/**
 * GET /api/example
 * Sample route demonstrating asyncHandler and res.success().
 * Replace with your own routes.
 */
app.get(
  '/api/example',
  asyncHandler(async (req, res) => {
    // throw ApiError.notFound('Resource not found') — errors are caught automatically
    return res.success({ message: 'Hello from express-response-engine! 🚀' });
  })
);

// ─── Global Error Handler ─────────────────────────────────────────────────────

// IMPORTANT: Must be registered AFTER all routes.
app.use(errorInterceptor());

// ─── Start Server ─────────────────────────────────────────────────────────────

app.listen(PORT, () => {
  console.log(\`🚀 Server is running at http://localhost:\${PORT}\`);
  console.log(\`❤️  Health check: http://localhost:\${PORT}/health\`);
});

module.exports = app;
`;
}

