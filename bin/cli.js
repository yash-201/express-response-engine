// ─── Main ────────────────────────────────────────────────────────────────────

function main() {
  const args = process.argv.slice(2);

  // Handle help flag at any position
  if (args.includes('--help') || args.includes('-h')) {
    printHelp();
    process.exit(0);
  }

  // Detect sub-command
  const command = args[0];
  if (!command || command === 'init' || command === 'create-server') {
    // OK — continue
  } else if (!command.startsWith('-')) {
    // Unknown positional that isn't a path will fall through as a custom path
  } else {
    // Flag-only invocation (e.g. --ts without "init") — treat as init
  }

  // Parse flags
  const useTs    = args.includes('--ts') || args.includes('--typescript');
  const force    = args.includes('--force') || args.includes('-f');

  // Determine custom output path from non-flag, non-command positional args
  const positionals = args.filter(
    (a) => !a.startsWith('-') && a !== 'init' && a !== 'create-server'
  );

  const cwd = process.cwd();

  let outputPath;

  if (positionals.length > 0) {
    // User provided explicit path
    outputPath = path.resolve(cwd, positionals[0]);
  } else {
    // Auto-detect: prefer src/ directory if it exists
    const srcDir = path.join(cwd, 'src');
    const hasSrc = fs.existsSync(srcDir) && fs.statSync(srcDir).isDirectory();
    const fileName = useTs ? 'index.ts' : 'index.js';
    outputPath = hasSrc ? path.join(srcDir, fileName) : path.join(cwd, fileName);
  }

  // Determine language from output extension when user provides explicit path
  const isTs = outputPath.endsWith('.ts') || useTs;
  const template = isTs ? generateTsTemplate() : generateJsTemplate();
  const relPath = path.relative(cwd, outputPath);

  // Guard: prevent overwriting without --force
  if (fs.existsSync(outputPath) && !force) {
    console.error(
      RED(`\n✖  File already exists: ${relPath}`) +
      `\n   Use ${YELLOW('--force')} to overwrite it.\n`
    );
    process.exit(1);
  }

  // Ensure parent directory exists
  const dir = path.dirname(outputPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  // Write the file
  fs.writeFileSync(outputPath, template, 'utf8');

  console.log(`
${GREEN('✔')} ${BOLD('Server file created successfully!')}

   ${CYAN(relPath)}

${BOLD('Next steps:')}
   1. Install dependencies (if not already):
      ${YELLOW('npm install express express-response-engine')}

   2. Start your server:
      ${YELLOW(`node ${relPath}`)}
${isTs ? `      ${YELLOW(`ts-node ${relPath}`)}` : ''}
   3. Check the health route:
      ${CYAN(`http://localhost:3000/health`)}

${BOLD('Customize the server:')}
   • Add your routes above the ${CYAN('errorInterceptor()')} line
   • Pass options to ${CYAN('responseInterceptor({ logger, encrypt })')} for logging & encryption
   • Use ${CYAN('asyncHandler(async (req, res) => { ... })')} to wrap async route handlers
   • Throw ${CYAN('ApiError.notFound()')} / ${CYAN('ApiError.badRequest()')} anywhere in your routes
`);
}

main();
