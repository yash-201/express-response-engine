/**
 * Capitalise the first letter of a word (e.g. "user" → "User")
 */
function cap(str) {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

// ── Validation ───────────────────────────────────────────────────────────────

function generateValidationJs(name) {
  return `'use strict';

// ─── ${cap(name)} Validation Rules ──────────────────────────────────────────────
// Requires: npm install express-validator

const { body, param } = require('express-validator');
const { validationResult } = require('express-validator');
const { ApiError, formatValidationError } = require('express-response-engine');

/**
 * validate() — Run after rule arrays in the router.
 * Reads validationResult and forwards a formatted ApiError to errorInterceptor.
 *
 * @example
 *   router.post('/', [...createRules, validate], controller.create);
 */
const validate = (req, res, next) => {
  const result = validationResult(req);
  if (!result.isEmpty()) {
    const formatted = result.array().map((e) => ({
      field: e.path || e.param || '',
      message: e.msg,
      value: e.value,
    }));
    return next(ApiError.validationError(formatted, 'Validation Error'));
  }
  next();
};

// ─── Rule Sets ───────────────────────────────────────────────────────────────

/** Rules for creating a ${name} */
const createRules = [
  body('name')
    .notEmpty().withMessage('Name is required')
    .isString().withMessage('Name must be a string')
    .trim(),
  body('email')
    .notEmpty().withMessage('Email is required')
    .isEmail().withMessage('Invalid email format')
    .normalizeEmail(),
  body('password')
    .notEmpty().withMessage('Password is required')
    .isLength({ min: 8 }).withMessage('Password must be at least 8 characters'),
  validate,
];

/** Rules for fetching / deleting a ${name} by ID */
const getByIdRules = [
  param('id')
    .notEmpty().withMessage('ID is required')
    .isInt({ min: 1 }).withMessage('ID must be a positive integer'),
  validate,
];

/** Rules for updating a ${name} */
const updateRules = [
  param('id')
    .notEmpty().withMessage('ID is required')
    .isInt({ min: 1 }).withMessage('ID must be a positive integer'),
  body('name').optional().isString().withMessage('Name must be a string').trim(),
  body('email').optional().isEmail().withMessage('Invalid email format').normalizeEmail(),
  validate,
];

module.exports = { validate, createRules, getByIdRules, updateRules };
`;
}

